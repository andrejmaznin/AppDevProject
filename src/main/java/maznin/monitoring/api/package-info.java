/**
 * Потоковая доставка данных и внешние форматы API.
 *
 * <h2>Назначение</h2>
 * Пакет отвечает за «исходящую» сторону системы: доставку измерений и
 * критических инцидентов подписчикам в реальном времени и расчёт
 * статистических характеристик по запросу.
 *
 * <h2>Состав</h2>
 * <ul>
 *   <li>{@link maznin.monitoring.api.StreamingService} — мост между PostgreSQL
 *       LISTEN/NOTIFY и реактивными подписчиками: единственный долгоживущий
 *       слушатель канала {@code measurements_channel} раздаёт события через
 *       внутренний {@code Sinks.Many};</li>
 *   <li>{@link maznin.monitoring.api.IncidentStreamingService} — аналогичный
 *       издатель для критических инцидентов, но события публикуются напрямую
 *       генератором (без участия БД), что даёт мгновенную доставку;</li>
 *   <li>{@link maznin.monitoring.api.StatisticsService} — агрегация
 *       статистики средствами SQL (среднее, выборочная дисперсия, квартили
 *       через {@code percentile_cont});</li>
 *   <li>{@link maznin.monitoring.api.SenMLMeasurement} — DTO измерения в
 *       формате SenML (RFC 8428): {@code n} — имя метрики, {@code u} —
 *       единица, {@code v} — значение, {@code t} — время;</li>
 *   <li>{@link maznin.monitoring.api.MetricStatistics} — DTO статистических
 *       характеристик одной метрики на интервале.</li>
 * </ul>
 *
 * <h2>Особенности</h2>
 * <ul>
 *   <li>Оба издателя используют {@code Sinks.many().multicast().directBestEffort()}:
 *       медленный подписчик не тормозит остальных, события для него
 *       отбрасываются (для живого дашборда потеря кадра допустима);</li>
 *   <li>подписка фильтруется по {@code patientId} — каждый SSE-клиент видит
 *       только события своего пациента;</li>
 *   <li>агрегирующий SQL опирается на BRIN-индекс по {@code measured_at} —
 *       диапазонные сканы по времени дешевы даже на больших объёмах.</li>
 * </ul>
 */
package maznin.monitoring.api;
