/**
 * Движок генерации телеметрии и отслеживания критических инцидентов.
 *
 * <h2>Назначение</h2>
 * Эмулирует датчики витальных показателей: для каждой пары
 * «пациент × метрика» работает отдельная задача на виртуальном потоке
 * Java 21, которая на каждом тике генерирует следующее значение, сохраняет
 * измерение в БД и следит за выходом значения из нормального диапазона.
 *
 * <h2>Состав (паттерны: Команда + Стратегия)</h2>
 * <ul>
 *   <li>{@link maznin.monitoring.engine.MetricGenerationEngine} — инициатор:
 *       реестр активных задач ({@code ConcurrentHashMap}) и их запуск/останов
 *       через {@code Executors.newVirtualThreadPerTaskExecutor()};</li>
 *   <li>{@link maznin.monitoring.engine.MetricGeneratorTask} — Команда:
 *       бесконечный цикл «сгенерировать → сохранить → проверить границы →
 *       уснуть на tickRate», плюс конечный автомат критического инцидента;</li>
 *   <li>{@link maznin.monitoring.engine.ValueGenerator} — Стратегия генерации
 *       следующего значения;</li>
 *   <li>{@link maznin.monitoring.engine.OrnsteinUhlenbeckGenerator} —
 *       реализация стратегии: стохастический процесс Орнштейна–Уленбека
 *       <i>x(t+1) = x(t) + Θ·(μ − x(t))·dt + σ·√dt·N(0,1)</i>;</li>
 *   <li>{@link maznin.monitoring.engine.MonitoringRestoreRunner} —
 *       восстановление мониторинга после перезапуска приложения по флагу
 *       {@code monitoringActive} в БД.</li>
 * </ul>
 *
 * <h2>Жизненный цикл критического инцидента</h2>
 * <ol>
 *   <li>значение вышло за границы — синхронный INSERT инцидента
 *       (гарантия фиксации в БД до уведомления) и публикация события;</li>
 *   <li>пока значение вне нормы — отслеживается пиковое отклонение от μ
 *       (в памяти, без записи);</li>
 *   <li>возврат в норму или останов мониторинга — проставляется
 *       {@code resolvedAt}, публикуется событие, асинхронный UPDATE.</li>
 * </ol>
 *
 * <h2>Особенности</h2>
 * <ul>
 *   <li>состояние инцидента — поле задачи, к нему обращается только её
 *       собственный виртуальный поток: синхронизация не нужна;</li>
 *   <li>σ каждой метрики масштабирована под ширину её нормального диапазона,
 *       чтобы инциденты были редкими событиями, а не шумом;</li>
 *   <li>блокирующие вызовы ({@code sleep}, {@code block()}) допустимы —
 *       виртуальные потоки дёшевы и не занимают потоки ОС при ожидании.</li>
 * </ul>
 */
package maznin.monitoring.engine;
