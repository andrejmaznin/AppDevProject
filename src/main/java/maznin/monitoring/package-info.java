/**
 * Patient Monitoring Dashboard — реактивная система мониторинга витальных
 * показателей пациентов.
 *
 * <h2>Назначение системы</h2>
 * Система эмулирует датчики физиологической телеметрии (частота пульса,
 * центральное венозное давление, температура тела), сохраняет измерения
 * в PostgreSQL, доставляет их в браузер в реальном времени через
 * Server-Sent Events, рассчитывает статистические характеристики и
 * автоматически фиксирует критические инциденты — выход показателя за
 * границы нормального диапазона.
 *
 * <h2>Технологический стек</h2>
 * <ul>
 *   <li>Java 21 — виртуальные потоки для задач генерации метрик;</li>
 *   <li>Spring Boot 3 + WebFlux — полностью неблокирующий веб-слой;</li>
 *   <li>Spring Data R2DBC — реактивный доступ к PostgreSQL;</li>
 *   <li>PostgreSQL — хранение + LISTEN/NOTIFY как шина событий измерений;</li>
 *   <li>JWT (jjwt) — аутентификация по RFC 7519 / RFC 6750.</li>
 * </ul>
 *
 * <h2>Структура пакетов</h2>
 * <ul>
 *   <li>{@link maznin.monitoring.api} — потоковая доставка (SSE), DTO внешних
 *       форматов (SenML), статистическая агрегация;</li>
 *   <li>{@link maznin.monitoring.auth} — выпуск JWT-токенов по учётным данным;</li>
 *   <li>{@link maznin.monitoring.engine} — эмулятор датчиков: генерация
 *       телеметрии (процесс Орнштейна–Уленбека);</li>
 *   <li>{@link maznin.monitoring.ingest} — точка приёма измерений в систему
 *       и детекция критических инцидентов (шов для замены источника данных);</li>
 *   <li>{@link maznin.monitoring.error} — преобразование исключений в ответы
 *       RFC 7807 Problem Details;</li>
 *   <li>{@link maznin.monitoring.patient} — доменная модель: пациенты,
 *       измерения, инциденты, REST-контроллер;</li>
 *   <li>{@link maznin.monitoring.security} — проверка JWT в цепочке фильтров
 *       WebFlux Security;</li>
 *   <li>{@link maznin.monitoring.user} — учётные записи операторов системы.</li>
 * </ul>
 *
 * <h2>Ключевые архитектурные решения</h2>
 * <ul>
 *   <li><b>Идентификаторы UUIDv7</b> присваиваются в коде приложения
 *       (монотонно растущие, дружественные к индексам БД); как следствие,
 *       сущности реализуют {@code Persistable} с явным флагом новизны;</li>
 *   <li><b>Поток измерений через БД</b>: генератор пишет только в PostgreSQL,
 *       а SSE-поток питается от LISTEN/NOTIFY — единственный источник истины,
 *       нет расхождений между сохранённым и доставленным;</li>
 *   <li><b>Ошибки в едином формате</b> RFC 7807 ({@code application/problem+json})
 *       на всех уровнях, включая 401/403 из цепочки безопасности.</li>
 * </ul>
 */
package maznin.monitoring;
