/**
 * Приём измерений в систему мониторинга — шов между источником данных
 * и бизнес-логикой.
 *
 * <h2>Назначение</h2>
 * Единственная точка, через которую измерения попадают в систему,
 * независимо от их происхождения. Сегодня продюсер —
 * {@link maznin.monitoring.engine эмулятор датчиков}; при интеграции с
 * реальной инфраструктурой больницы (шина данных HL7/MQTT и т.п.) адаптер
 * шины вызывает тот же {@code ingest()} — и вся остальная система
 * (персистентность, детекция инцидентов, SSE-доставка, статистика)
 * продолжает работать без изменений.
 *
 * <h2>Состав</h2>
 * <ul>
 *   <li>{@link maznin.monitoring.ingest.MeasurementIngestService} —
 *       Фасад приёма: «измерение вошло в систему» = сохранение в БД
 *       + детекция инцидентов; также принимает сигнал о завершении
 *       потока метрики ({@code streamClosed});</li>
 *   <li>{@link maznin.monitoring.ingest.CriticalIncidentDetector} —
 *       правило предметной области «значение вне нормы — критический
 *       инцидент»: ведёт состояние активных эпизодов по парам
 *       пациент×метрика, пишет {@code critical_incidents} и публикует
 *       события подписчикам.</li>
 * </ul>
 *
 * <h2>Контракт последовательности</h2>
 * Для корректного детектирования вызовы {@code ingest}/{@code streamClosed}
 * по одной паре «пациент × метрика» должны поступать последовательно
 * (из одного потока-продюсера) — это естественно выполняется и для задач
 * эмулятора (один виртуальный поток на метрику), и для упорядоченного
 * потребления из шины. Разные пары полностью независимы.
 */
